package com.sports.management.gateway;

import com.sun.net.httpserver.HttpServer;
import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.webmvc.test.autoconfigure.AutoConfigureMockMvc;
import org.springframework.http.HttpHeaders;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.test.web.servlet.MvcResult;

import java.io.IOException;
import java.io.OutputStream;
import java.net.InetSocketAddress;
import java.nio.charset.StandardCharsets;
import java.util.List;
import java.util.concurrent.CopyOnWriteArrayList;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.options;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.header;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

@SpringBootTest(properties = {
        "eureka.client.enabled=false",
        "eureka.client.register-with-eureka=false",
        "eureka.client.fetch-registry=false",
        "app.cors.allowed-origins=http://localhost:8080"
})
@AutoConfigureMockMvc
class GatewayRequestIdPropagationTest {

    private static HttpServer downstreamServer;
    private static int downstreamPort;
    private static final List<String> receivedRequestIds = new CopyOnWriteArrayList<>();

    @Autowired
    private MockMvc mockMvc;

    @DynamicPropertySource
    static void registerSimpleDiscovery(DynamicPropertyRegistry registry) throws IOException {
        if (downstreamServer == null) {
            downstreamServer = HttpServer.create(new InetSocketAddress("127.0.0.1", 0), 0);
            downstreamServer.createContext("/api/v1/tournaments", exchange -> {
                String incomingReqId = exchange.getRequestHeaders().getFirst("X-Request-Id");
                if (incomingReqId != null) {
                    receivedRequestIds.add(incomingReqId);
                }
                // Downstream co tinh tra X-Request-Id khac de kiem tra Gateway bo qua, khong gui trung header
                exchange.getResponseHeaders().set("Content-Type", "application/json");
                exchange.getResponseHeaders().set("X-Request-Id", "downstream-different-id");
                byte[] body = ("{\"receivedRequestId\":\"" + (incomingReqId == null ? "" : incomingReqId) + "\"}")
                        .getBytes(StandardCharsets.UTF_8);
                exchange.sendResponseHeaders(200, body.length);
                try (OutputStream os = exchange.getResponseBody()) {
                    os.write(body);
                }
            });
            downstreamServer.start();
            downstreamPort = downstreamServer.getAddress().getPort();
        }
        registry.add("spring.cloud.discovery.client.simple.instances.tournament-service[0].uri",
                () -> "http://127.0.0.1:" + downstreamPort);
    }

    @AfterAll
    static void stopServer() {
        if (downstreamServer != null) {
            downstreamServer.stop(0);
        }
    }

    @BeforeEach
    void clearCapturedIds() {
        receivedRequestIds.clear();
    }

    @Test
    void requestWithoutHeader_generatesSingleXRequestIdAndForwardsExactIdToDownstream() throws Exception {
        MvcResult result = mockMvc.perform(get("/api/v1/tournaments"))
                .andExpect(status().isOk())
                .andReturn();

        List<String> respHeaders = result.getResponse().getHeaders("X-Request-Id");
        assertEquals(1, respHeaders.size(), "Gateway response must contain exactly one X-Request-Id header");
        String generatedId = respHeaders.get(0);
        assertNotNull(generatedId);
        assertFalse(generatedId.isBlank());

        assertEquals(1, receivedRequestIds.size());
        assertEquals(generatedId, receivedRequestIds.get(0),
                "Downstream service must receive the exact X-Request-Id generated by Gateway");
    }

    @Test
    void requestWithHeader_preservesSingleXRequestIdEvenWhenDownstreamReturnsDifferentHeader_andDoesNotBreakCors() throws Exception {
        String traceId = "gw-trace-2026-001";
        MvcResult result = mockMvc.perform(get("/api/v1/tournaments")
                        .header("X-Request-Id", traceId))
                .andExpect(status().isOk())
                .andReturn();

        List<String> respHeaders = result.getResponse().getHeaders("X-Request-Id");
        assertEquals(List.of(traceId), respHeaders,
                "Gateway must keep client X-Request-Id without duplicating downstream X-Request-Id");
        assertEquals(List.of(traceId), receivedRequestIds);

        mockMvc.perform(options("/api/v1/tournaments")
                        .header(HttpHeaders.ORIGIN, "http://localhost:8080")
                        .header(HttpHeaders.ACCESS_CONTROL_REQUEST_METHOD, "GET"))
                .andExpect(status().isOk())
                .andExpect(header().string(HttpHeaders.ACCESS_CONTROL_ALLOW_ORIGIN, "http://localhost:8080"))
                .andExpect(header().exists("X-Request-Id"));
    }
}
